/** Normalize, mirror and return a usable template grid (array of 7 strings) */
export function templateGrid(tpl, flipX, flipY) {
  let rows = tpl.rows.map((r) => (r + '.............').slice(0, 13));
  while (rows.length < 7) rows.push('.............');
  rows = rows.slice(0, 7);
  if (flipX) rows = rows.map((r) => r.split('').reverse().join(''));
  if (flipY) rows = rows.slice().reverse();
  return rows;
}
